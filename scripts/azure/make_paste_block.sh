#!/usr/bin/env bash
# Regenerate PASTE_BLOCK.sh from the files in scripts/azure (quoted heredocs, no auth needed to paste).
set -euo pipefail
cd "$(dirname "$0")"
FILES=(reencode.sh resample.py check_nusc.py export_fit.py run_all.sh)
{
  echo '#!/usr/bin/env bash'
  echo "# ONE paste block for the Azure VM: recreates scripts/azure (no git auth needed) and runs it."
  echo "# Generated by scripts/azure/make_paste_block.sh at commit-time $(date -u +%Y-%m-%dT%H:%MZ). SUPERSEDES earlier PASTE_BLOCK versions."
  echo "# Exports fit_500/fit_resampled (PRIMARY, nearest-timestamp 1/12 s grid) + fit_500/fit_raw (secondary) -> lhf5_fit_500.tar"
  echo 'conda activate azureml_py38 2>/dev/null || source activate azureml_py38 2>/dev/null || true'
  echo 'mkdir -p ~/lhf5_azure && cd ~/lhf5_azure && rm -rf fit_500 lhf5_fit_500.tar'
  for f in "${FILES[@]}"; do
    tag="LHF5_EOF_${f//./_}"
    if grep -q "^${tag}\$" "$f"; then echo "delimiter clash in $f" >&2; exit 1; fi
    echo "cat > $f <<'$tag'"; cat "$f"; [[ -z "$(tail -c1 "$f")" ]] || echo; echo "$tag"
  done
  echo 'chmod +x *.sh && nohup bash run_all.sh > run_all.log 2>&1 &'
  echo 'tail -f run_all.log'
} > PASTE_BLOCK.sh
bash -n PASTE_BLOCK.sh && echo "PASTE_BLOCK.sh OK ($(wc -l < PASTE_BLOCK.sh) lines)"
